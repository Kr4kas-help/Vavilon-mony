export default function Page() {
  const [selected, setSelected] = useState<number | null>(null);
  const [choice, setChoice] = useState<number | null>(null);

  if (selected !== null) {
    const lesson = lessons[selected];
    const correct = choice === lesson.answer;
    return (
      <div className="space-y-6">
        <button type="button" className="btn btn-ghost" onClick={() => { setSelected(null); setChoice(null); }}>← Все уроки</button>
        <div className="card p-6">
          <p className="text-ink/60">Урок {selected + 1} из 7</p>
          <h1 className="mt-2">{lesson.title}</h1>
          <div className="mt-5 rounded-xl border border-[rgba(217,164,65,0.35)] bg-white/5 p-4">
            <p className="font-semibold text-[#EDB468]">Золотое правило</p>
            <p className="mt-2 text-lg">{lesson.rule}</p>
          </div>
          <h2 className="mt-7">{lesson.hero}</h2>
          <p className="prose-line mt-2">{lesson.book}</p>
          <h2 className="mt-7">Попробуйте в жизни</h2>
          <p className="prose-line mt-2">{lesson.situation}</p>
          <div className="mt-4 space-y-3">
            {lesson.options.map((option, i) => (
              <button key={option} type="button" className="choice w-full text-left" data-on={choice === i} onClick={() => setChoice(i)}>
                <span aria-hidden className="mt-1 inline-block h-5 w-5 shrink-0 rounded-full border-2 border-spruce" style={{ background: choice === i ? "#D9A441" : "transparent" }} />
                <span>{option}</span>
              </button>
            ))}
          </div>
          {choice !== null && (
            <div className={"mt-5 rounded-xl p-4 " + (correct ? "bg-emerald-500/15" : "bg-rose-500/15")}>
              <strong>{correct ? "Правильный выбор" : "Посмотрите на правило ещё раз"}</strong>
              <p className="mt-1">{lesson.explanation}</p>
              {!correct && <button type="button" className="btn btn-ghost mt-3" onClick={() => setChoice(null)}>Попробовать ещё</button>}
            </div>
          )}
        </div>
      </div>
    );
  }

  return (
    <div className="space-y-6">
      <div>
        <h1>Обучение</h1>
        <p className="prose-line mt-2 text-ink/75">Семь коротких уроков по золотым правилам денег. Прочитайте пример, затем решите похожую ситуацию из жизни.</p>
      </div>
      <div className="grid gap-4">
        {lessons.map((lesson, i) => (
          <button key={lesson.title} type="button" className="card w-full p-5 text-left transition hover:-translate-y-0.5" onClick={() => setSelected(i)}>
            <span className="text-ink/60">Урок {i + 1}</span>
            <h2 className="mt-1">{lesson.title}</h2>
            <p className="prose-line mt-2 text-ink/70">{lesson.rule}</p>
            <span className="mt-3 inline-block text-[#EDB468]">Открыть урок →</span>
          </button>
        ))}
      </div>
      <Link href="/rules" className="btn btn-gold">Все золотые правила</Link>
    </div>
  );
}
